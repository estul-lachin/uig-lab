"""Generate config/access.events: one morning of web-server-01's nginx access log, in a fixed order.

Run from the lab directory: python3 tools/make_feed.py > config/access.events
Line format: ip|METHOD url|status|size|user agent
"""
import random

r = random.Random(31103)
BROWSER = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130.0 Safari/537.36"
SQLMAP = "sqlmap/1.8.4#stable (https://sqlmap.org)"
CURL = "curl/8.5.0"
SCAN = "Mozilla/5.0 (compatible; Nmap Scripting Engine)"

SQLI = ["/product.php?id=1%20union%20select%201,2,3--", "/product.php?id=1'%20or%201=1--",
        "/product.php?id=1%20union%20select%20user,password%20from%20users--",
        "/login.php?user=admin'%20union%20select%20null,null--", "/product.php?id=2+union+select+1,2,3",
        "/cart.php?item=5%20and%201=1%20union%20select%20version()--",
        "/product.php?id=1;exec%20xp_cmdshell('whoami')", "/product.php?id=3%20union%20all%20select%20null,null,null--",
        "/order.php?id=7%20where%201=1"]
XSS = ["/comment.php?text=%3Cscript%3Ealert(1)%3C/script%3E", "/profile.php?name=%3Cscript%3Edocument.cookie%3C/script%3E",
       "/contact.php?msg=%3Ciframe%20src=//evil.example%3E", "/comment.php?text=%3CIMG%20SRC=javascript:alert(1)%3E",
       "/profile.php?bio=%3Csvg%20ONLOAD=alert(1)%3E%20ONLOAD=x", "/feedback.php?q=%3Cscript%3Efetch(1)%3C%2Fscript%3E",
       "/contact.php?msg=%3CINPUT%20onfocus=alert(1)%3E"]
TRAV = ["/download.php?file=../../../../etc/passwd", "/download.php?file=../../../etc/shadow",
        "/download.php?file=../../../../proc/self/environ", "/static/../../../../etc/hosts",
        "/download.php?file=....//....//etc/passwd../..", "/download.php?file=%2E%2E%2E%2E/etc/group"]
ENC = ["/download.php?file=..%2F..%2F..%2Fetc%2Fpasswd", "/download.php?file=..%2F..%2F..%2F..%2Fetc%2Fshadow",
       "/download.php?file=%2e%2e%2f%2e%2e%2fvar%2fwww%2f.env", "/download.php?file=..%5C..%5Cweb.config"]
PAGES = ["/", "/index.php", "/product.php?id=%d", "/cart.php", "/static/app.css", "/static/app.js",
         "/images/logo.png", "/download.php?file=catalog-2026.pdf", "/search.php?search=brake+pads", "/login.php"]
PROBES = ["/.env", "/wp-login.php", "/phpmyadmin/", "/.git/config", "/admin/", "/backup.zip", "/server-status",
          "/config.php.bak", "/.aws/credentials", "/api/v1/users", "/xmlrpc.php", "/actuator/health",
          "/vendor/phpunit/", "/.DS_Store", "/console", "/test.php", "/old/", "/db.sql", "/.htpasswd", "/cgi-bin/"]

ev = []
def add(ip, url, status, ua, size=None):
    ev.append((ip, "GET " + url, status, size or r.randint(120, 900), ua))

# Single-technique attackers
for u in SQLI: add("203.0.113.10", u, r.choice([403, 500]), SQLMAP)
for u in XSS: add("198.51.100.23", u, r.choice([400, 403]), BROWSER)
for u in TRAV: add("203.0.113.77", u, r.choice([403, 404]), CURL)
for u in ENC: add("203.0.113.77", u, 404, CURL)
# One actor spread across all three techniques: never first in any single one
for u in SQLI[:5]: add("192.0.2.45", u.replace("id=1", "id=4"), 403, BROWSER)
for u in XSS[:4]: add("192.0.2.45", u, 403, BROWSER)
for u in TRAV[:4]: add("192.0.2.45", u, 404, BROWSER)
# A scanner: only 404s, no technique at all
for u in PROBES: add("198.51.100.99", u, 404, SCAN)
# Normal customers
for i in range(45):
    p = r.choice(PAGES)
    add("10.20.%d.%d" % (r.randint(1, 3), r.randint(10, 60)), p % r.randint(1, 40) if "%d" in p else p, 200, BROWSER)

r.shuffle(ev)
# The quiet one, at the end: two blocked probes, then a SQL injection that worked, then an encoded
# traversal that worked (and no rule notices)
tail = [("198.51.100.200", "GET /order.php?id=7%20union%20select%201--", 403, 162, CURL),
        ("198.51.100.200", "GET /order.php?id=7%20union%20select%20null,null--", 403, 162, CURL),
        ("198.51.100.200", "GET /order.php?id=7%20union%20select%20email,password_hash%20from%20customers--", 200, 18422, CURL),
        ("203.0.113.77", "GET /download.php?file=..%2F..%2F..%2Fetc%2Fnginx%2Fconf.d%2Fshop.conf", 200, 2311, CURL)]
ev[len(ev) - 10:len(ev) - 10] = tail
print("# ip|request|status|size|user agent (generated by tools/make_feed.py)")
for e in ev:
    print("%s|%s|%s|%s|%s" % e)
