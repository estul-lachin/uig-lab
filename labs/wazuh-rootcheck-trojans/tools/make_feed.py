        T % ("/usr/bin/ls", r"bash|^/bin/sh|dev/[^clu]|\.tmp/lsfile|duarawkz|/prof|/security|file\.h"),
        DEV % "/dev/.lib/lib.so", DEV % "/dev/shm/.ice",
        HDIR % ("/usr/lib/.sshd-cache", 4, 2), PORT % 31337,
